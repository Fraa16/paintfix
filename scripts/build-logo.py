# ---- standalone SVG files ----
out = ROOT / "public/brand"
out.mkdir(parents=True, exist_ok=True)


def svg(viewbox, body):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}">{body}</svg>\n'


def ring(m, color):
    r = m["ring"]
    return f'<circle cx="{r["cx"]}" cy="{r["cy"]}" r="{r["r"]}" fill="none" stroke="{color}" stroke-width="{r["strokeWidth"]}"/>'


for name, color in (("graphite", GRAPHITE), ("white", "#FFFFFF")):
    m = marks["wordmark"]
    (out / f"paintfix-wordmark-{name}.svg").write_text(svg(m["viewBox"], f'<path fill="{color}" d="{m["paths"][0]["d"]}"/>'))
    m = marks["monogram"]
    (out / f"paintfix-monogram-{name}.svg").write_text(svg(m["viewBox"], f'<path fill="{color}" d="{m["paths"][0]["d"]}"/>'))

m = marks["seal"]
(out / "paintfix-aviation-seal-gold.svg").write_text(svg(m["viewBox"], ring(m, GOLD) + f'<path fill="{GOLD}" d="{m["paths"][0]["d"]}"/>'))

m = marks["aviationLockup"]
for name, primary in (("on-navy", "#F5F3EE"), ("on-light", NAVY)):
    body = ring(m, GOLD)
    for p in m["paths"]:
        fill = GOLD if p["role"] in ("seal", "accent") else primary
        body += f'<path fill="{fill}" d="{p["d"]}"/>'
    (out / f"paintfix-aviation-lockup-{name}.svg").write_text(svg(m["viewBox"], body))

