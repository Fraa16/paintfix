"""Builds outlined logo marks from the brand typeface (Mona Sans variable, OFL).

Outputs:
  src/components/global/logo-paths.ts  (inline use in the site, currentColor)
  public/brand/*.svg                   (download / GBP / print hand-off)

Run: python3 scripts/build-logo.py   (needs: pip install fonttools brotli)
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "node_modules/@fontsource-variable/mona-sans/files/mona-sans-latin-wdth-normal.woff2"
GOLD = "#C2A36B"
NAVY = "#0E1830"
GRAPHITE = "#1A1D21"

_cache = {}


def instance(wdth, wght):
    key = (wdth, wght)
    if key not in _cache:
        f = TTFont(FONT)
        _cache[key] = instancer.instantiateVariableFont(f, {"wdth": wdth, "wght": wght})
    return _cache[key]


def outline(text, wdth, wght, size, tracking=0.0, x=0.0, baseline=0.0):
    """Return (svg path d, advance width) for text set at `size` px with tracking in em."""
    font = instance(wdth, wght)
    upm = font["head"].unitsPerEm
    scale = size / upm
    cmap = font.getBestCmap()
    gs = font.getGlyphSet()
    hmtx = font["hmtx"]
    pen = SVGPathPen(gs)
    cursor = x
    for i, ch in enumerate(text):
        name = cmap[ord(ch)]
        tpen = TransformPen(pen, (scale, 0, 0, -scale, cursor, baseline))
        gs[name].draw(tpen)
        cursor += hmtx[name][0] * scale
        if i < len(text) - 1:
            cursor += tracking * size
    return pen.getCommands(), cursor - x


def cap_height(wdth, wght, size):
    font = instance(wdth, wght)
    return font["OS/2"].sCapHeight * size / font["head"].unitsPerEm


marks = {}

# 1) Master wordmark: calm, engineered, slightly extended.
W1 = dict(wdth=112, wght=700)
d, adv = outline("PAINTFIX", **W1, size=100, tracking=0.05)
ch = cap_height(**W1, size=100)
marks["wordmark"] = {"viewBox": f"0 {-ch:.1f} {adv:.1f} {ch:.1f}", "paths": [{"d": d}]}

# 2) PF monogram (expanded).
W2 = dict(wdth=125, wght=620)
d, adv = outline("PF", **W2, size=100, tracking=0.02)
ch2 = cap_height(**W2, size=100)
marks["monogram"] = {"viewBox": f"0 {-ch2:.1f} {adv:.1f} {ch2:.1f}", "paths": [{"d": d}]}

# 3) Aviation seal: thin ring + monogram centred.
R = 100
ring_stroke = 2.2
mono_w = adv
W2S = dict(wdth=125, wght=470)  # lighter cut for the seal: jewellery, not a stamp
_, mono_w_light = outline("PF", **W2S, size=100, tracking=0.03)
mono_scale = 1.02 * R / mono_w_light  # monogram spans ~51% of the ring diameter
d_seal, adv_seal = outline("PF", **W2S, size=100 * mono_scale, tracking=0.03)
ch_seal = cap_height(**W2S, size=100 * mono_scale)
d_seal, _ = outline("PF", **W2S, size=100 * mono_scale, tracking=0.03, x=R - adv_seal / 2, baseline=R + ch_seal / 2)
marks["seal"] = {
    "viewBox": f"0 0 {2*R} {2*R}",
    "paths": [{"d": d_seal}],
    "ring": {"cx": R, "cy": R, "r": R - ring_stroke, "strokeWidth": ring_stroke},
}

# 4) Aviation lockup: seal + "PAINTFIX AVIATION" on one line.
H = 200  # lockup height = seal diameter
text_size = 62
W3 = dict(wdth=125, wght=600)
W4 = dict(wdth=125, wght=380)
ch3 = cap_height(**W3, size=text_size)
base = H / 2 + ch3 / 2
gap = 44
d_pf, adv_pf = outline("PAINTFIX", **W3, size=text_size, tracking=0.12, x=2 * R + gap, baseline=base)
d_av, adv_av = outline("AVIATION", **W4, size=text_size, tracking=0.12, x=2 * R + gap + adv_pf + text_size * 0.55, baseline=base)
total = 2 * R + gap + adv_pf + text_size * 0.55 + adv_av
marks["aviationLockup"] = {
    "viewBox": f"0 0 {total:.1f} {H}",
    "paths": [{"d": d_seal, "role": "seal"}, {"d": d_pf, "role": "primary"}, {"d": d_av, "role": "accent"}],
    "ring": {"cx": R, "cy": R, "r": R - ring_stroke, "strokeWidth": ring_stroke},
}

